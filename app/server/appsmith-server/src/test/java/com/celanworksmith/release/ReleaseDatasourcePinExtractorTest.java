    @Test
    void separatesMissingDatasourceIdReasonFromPathAndIncludesOnlyActionIdentity() {
        NewAction query = action("query-id", datasource(null, "unknown", List.of()));
        query.getUnpublishedAction().setName("queryWithMissingReference");
        query.getUnpublishedAction()
                .getDatasource()
                .getDatasourceConfiguration()
                .setUrl("secret-url");

        var diagnostic = extractActions(ontologyPluginService("ontology-plugin"), List.of(), query)
                .diagnostics()
                .get(0);

        assertThat(diagnostic.path())
                .isEqualTo("unpublishedActions[actionId=query-id].unpublishedAction.datasource.id");
        assertThat(diagnostic.message()).isEqualTo("Datasource identifier is missing");
        assertThat(diagnostic.message()).doesNotContain("unpublishedActions[");
        assertThat(diagnostic.details())
                .containsExactlyInAnyOrderEntriesOf(
                        Map.of("actionId", "query-id", "actionName", "queryWithMissingReference"));
    }

    @Test
    void reportsExplicitPluginAndPropertyPathsWithoutRepeatingActionPaths() {
        NewAction missingPlugin = action("a", datasource("db", null, List.of()));
        NewAction conflictingPlugin = typedAction("b", datasource("db", "postgres", List.of()), "other", PluginType.DB);
        NewAction missingProperty = action(
                "c",
                datasource(
                        "ontology",
                        "ontology-plugin",
                        ontologyProperties("1").stream()
                                .filter(property -> !"projectId".equals(property.getKey()))
                                .toList()));

        var diagnostics = extractActions(
                        ontologyPluginService("ontology-plugin"),
                        List.of(),
                        missingPlugin,
                        conflictingPlugin,
                        missingProperty)
                .diagnostics();

        assertThat(diagnostics)
                .extracting("path")
                .containsExactly(
                        "unpublishedActions[actionId=a].unpublishedAction.datasource.pluginId",
                        "unpublishedActions[actionId=b].unpublishedAction.datasource.pluginId",
                        "unpublishedActions[actionId=c].unpublishedAction.datasource.datasourceConfiguration.properties.projectId");
        assertThat(diagnostics).allSatisfy(diagnostic -> {
            assertThat(diagnostic.message()).doesNotContain("unpublishedActions[");
            assertThat(diagnostic.details()).containsOnlyKeys("actionId");
        });
    }

