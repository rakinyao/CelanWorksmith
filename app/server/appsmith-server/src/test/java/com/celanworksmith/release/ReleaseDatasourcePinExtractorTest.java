    @Test
    void skipsPluginOnlyAndAutoGeneratedJsDatasourcesWithoutChangingCandidateActions() {
        PluginService plugins = ontologyPluginService("ontology-plugin");
        registerPlugin(plugins, "js-id", "js-plugin", PluginType.JS);
        NewAction js = typedAction("js", datasource(null, "js-id", List.of()), "js-id", PluginType.JS);
        js.getUnpublishedAction().getDatasource().setDatasourceConfiguration(null);
        NewAction generated = typedAction("generated", new Datasource(), "js-id", PluginType.JS);
        generated.getUnpublishedAction().getDatasource().setIsAutoGenerated(true);
        NewActionRepository repository = Mockito.mock(NewActionRepository.class);
        Mockito.when(repository.findByApplicationId("app-1", AclPermission.READ_ACTIONS))
                .thenReturn(Flux.just(js, generated));
        ApplicationReleaseCandidate candidate = candidate(js, generated);

        ReleaseDatasourcePinExtractionResult result =
                extractor(repository, plugins).extract(candidate).block();

        assertThat(result.diagnostics()).isEmpty();
        assertThat(result.pins()).isEmpty();
        assertThat(candidate.unpublishedActions()).containsExactly(js, generated);
        assertThat(js.getUnpublishedAction().getDatasource().getId()).isNull();
        assertThat(generated.getUnpublishedAction().getDatasource().getId()).isNull();
        Mockito.verify(plugins, Mockito.times(1)).findById("js-id");
    }

