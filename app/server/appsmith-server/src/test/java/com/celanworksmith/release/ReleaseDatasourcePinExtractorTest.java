    @Test
    void keepsOntologyConflictAndDiagnosticOrderingInMixedNativeResources() {
        PluginService plugins = ontologyPluginService("ontology-plugin");
        registerPlugin(plugins, "js-id", "js-plugin", PluginType.JS);
        NewAction js = typedAction("js", datasource(null, "js-id", List.of()), "js-id", PluginType.JS);
        NewAction first = action("a", datasource("ontology-1", "ontology-plugin", ontologyProperties("1")));
        NewAction second = action("z", datasource("ontology-1", "ontology-plugin", ontologyProperties("2")));
        NewAction saved = action("saved", datasource("db-1", "postgres", List.of()));
        NewAction invalid = action("b", datasource(null, "unknown", List.of()));
        ReleaseDatasourcePinExtractionResult result =
                extractActions(plugins, List.of(), second, js, invalid, saved, first);
        ReleaseDatasourcePinExtractionResult reversed =
                extractActions(plugins, List.of(), first, saved, invalid, js, second);

        assertThat(result.pins()).extracting(ReleaseDatasourcePin::datasourceId).containsExactly("db-1");
        assertThat(result.diagnostics())
                .extracting("code")
                .containsExactly("RELEASE_DATASOURCE_CONFIGURATION_MALFORMED", "RELEASE_DATASOURCE_CONFLICT");
        assertThat(reversed).isEqualTo(result);
    }

    private static ReleaseDatasourcePinExtractionResult extractActions(
            PluginService plugins, List<Datasource> datasources, NewAction... actions) {
        NewActionRepository repository = Mockito.mock(NewActionRepository.class);
        Mockito.when(repository.findByApplicationId("app-1", AclPermission.READ_ACTIONS))
                .thenReturn(Flux.just(actions));
        return extractor(repository, plugins)
                .extract(candidate(datasources, actions))
                .block();
    }

    private static NewAction typedAction(String id, Datasource datasource, String pluginId, PluginType type) {
        NewAction action = action(id, datasource);
        action.setPluginId(pluginId);
        action.setPluginType(type);
        return action;
    }

